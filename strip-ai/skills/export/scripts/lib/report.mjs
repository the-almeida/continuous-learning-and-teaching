// The report next to the zip. The script writes every factual section
// (checks, removals, redactions, decisions, what was not exported); Claude
// only fills the sections marked TODO. Finalize then proves the report
// itself leaks nothing.
export const TODO = '<!-- strip-ai:todo -->'

function table(header, rows) {
  if (!rows.length) return '_None._\n'
  const esc = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
  return [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`)].join('\n') + '\n'
}

function list(items, limit = 50) {
  if (!items.length) return '_None._\n'
  const shown = items.slice(0, limit).map((i) => `- ${i}`)
  if (items.length > limit) shown.push(`- … and ${items.length - limit} more`)
  return shown.join('\n') + '\n'
}

const exit = (run) => (!run ? 'not run' : run.timedOut ? 'timed out' : run.exitCode === 0 ? 'pass' : `fail (exit ${run.exitCode})`)

/** data: everything the CLI knows, with paths already cleaned of identity. */
export function buildReport(d) {
  const out = []
  out.push(`# ${d.rootName}: clean export report\n`)
  out.push('<!-- Generated by strip-ai. Replace each TODO marker with content; leave the rest as is. -->\n')
  out.push(
    table(
      ['', ''],
      [
        ['Zip', `\`${d.zipName}\``],
        ['SHA-256', `\`${d.sha256}\``],
        ['Files', `${d.files} (${d.bytes} bytes)`],
        ['Verified by', `${d.verifier}${d.independent ? '' : ' (not independent)'}, ${d.files} files compared byte for byte, then scanned again`],
        ['Project', d.mode === 'third-party' ? 'third-party: contributors\' full names and emails redacted, license notices kept verbatim' : 'own project'],
        ['Date', d.date],
      ],
    ),
  )
  if (d.shallow) out.push('> ⚠️ The source was a shallow clone: authors of older commits were not collected as identities.\n')

  if (d.languages) {
    out.push('## Languages\n')
    const rows = [...d.languages.kept.map((l) => [l.language, l.type, l.files, 'kept']), ...d.languages.excluded.map((l) => [l.language, l.type, l.files, 'excluded by the user'])]
    out.push(table(['Language', 'Type', 'Files', 'Decision'], rows))
  }

  out.push('## Checks\n')
  if (d.noChecks) out.push(`No checks were run: ${d.noChecks}\n`)
  else {
    out.push(table(['Command', 'Before cleaning', 'After cleaning'], d.checks.map((c) => [`\`${c.command}\``, exit(c.baseline), exit(c.final)])))
    const approvals = [...new Set(d.checks.flatMap((c) => [c.baseline?.approval, c.final?.approval]).filter(Boolean))]
    if (approvals.length) out.push(`Third-party code was run with the user's approval (${approvals.join('; ')}), without the operator's credentials (scrubbed environment, throwaway home).\n`)
  }

  out.push('## Removed AI tooling\n')
  out.push(list(d.removedAi.map((p) => `\`${p}\``)))
  if (d.aiNames.length) out.push(`Commands, skills and agents removed with them: ${d.aiNames.map((n) => `\`${n}\``).join(', ')}\n`)

  out.push('## AI references cleaned\n')
  out.push(`${TODO} One line per file: what was removed or rewritten. Project renames (old name masked).\n`)

  out.push('## Redactions\n')
  out.push(table(['Category', 'Original (masked)', 'Placeholder', 'Occurrences', 'Files'], d.redactions.map((r) => [r.category, r.original, r.placeholder, r.count, r.files.length])))
  if (d.renamed.length) out.push(`Files renamed:\n\n${list(d.renamed.map((r) => `\`${r}\``))}`)
  if (d.replacedDocuments.length) out.push(`Documents replaced by placeholders:\n\n${list(d.replacedDocuments.map((r) => `\`${r.file}\`: ${r.reasons.join(', ')}`))}`)
  if (d.strippedMetadata.length) out.push(`Image metadata stripped (photos may now display rotated):\n\n${list(d.strippedMetadata.map((r) => `\`${r.file}\`: ${r.removed.join(', ')}`))}`)
  if (d.normalized.length) out.push(`Line endings converted from CRLF to LF (git stores them as LF): ${d.normalized.length} file(s).\n`)
  if (d.keptNotices?.length) out.push(`License notices kept verbatim, as their licenses require:\n\n${list(d.keptNotices.map((f) => `\`${f}\``))}Copyright lines in file headers were kept verbatim too.\n`)

  out.push('## Tests coupled to PII\n')
  out.push(`${TODO} Table: Test (file › name) | Depended on | How it broke | Fix. Write "None." if no test broke.\n`)

  out.push('## Decisions\n')
  out.push(table(['Rule', 'File', 'Value', 'Reason'], d.decisions.map((x) => [x.rule, x.file, x.value, x.reason])))

  out.push('## Files changed by the export\n')
  out.push(`Modified: ${d.changes.modified}. Deleted: ${d.changes.deleted}. Added: ${d.changes.added.length}.\n`)
  if (d.changes.added.length) out.push(list(d.changes.added.map((p) => `\`${p}\``)))

  out.push('## Not exported\n')
  out.push(
    list([
      ...(d.skipped.symlinksOutside ? [`Symlinks pointing outside the project: ${d.skipped.symlinksOutside}`] : []),
      ...d.skipped.submodules.map((s) => `Submodule (its files belong to another repository): \`${s}\``),
      ...Object.entries(d.skipped.heavyUntracked).map(([dir, n]) => `Untracked files under \`${dir}/\`: ${n}`),
      ...(d.skipped.missingInWorktree ? [`Tracked files deleted in the working tree: ${d.skipped.missingInWorktree}`] : []),
    ]),
  )

  out.push('## Not verified\n')
  out.push(`${TODO} Suites skipped and why. Files over the scan limit and how they were checked. Write "Nothing." if everything was verified.\n`)
  return out.join('\n')
}
